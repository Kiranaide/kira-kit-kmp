val LocalKiraColors = staticCompositionLocalOf { KiraThemes.Default.light }
val LocalKiraRadius = staticCompositionLocalOf { KiraThemes.Default.radius }

object KiraTheme {
    val colors: KiraColorScheme
        @Composable get() = LocalKiraColors.current

    val radius: KiraRadiusScale
        @Composable get() = LocalKiraRadius.current
}

@Composable
fun KiraTheme(
    theme: KiraThemeDefinition = KiraThemes.Default,
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit,
) {
    val colors = if (darkTheme) theme.dark else theme.light
    CompositionLocalProvider(
        LocalKiraColors provides colors,
        LocalKiraRadius provides theme.radius,
        content = content,
    )
}
